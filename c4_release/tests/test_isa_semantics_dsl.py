    spec = _bp_like_spec()
    bundle = cross_step_carry(spec)
    assert isinstance(bundle, CrossStepCarryBundle)
    assert bundle.spec is spec
    # The carry head WRITES only the _PREV band; READS the cross-step value srcs.
