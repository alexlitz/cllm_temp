def test_head_write_count_advances_slot_and_dim():
    """A ``count`` directive advances BOTH slot and dim by default (the V/O
    per-cell copy block)."""
    out = _expand_head_writes(
        (HeadWrite(10, "SRC", 1.0, count=3),),
        lambda n: {"SRC": 50}[n], kind="proj")
    assert [(w.slot, w.dim, w.weight) for w in out] == [
        (10, 50, 1.0), (11, 51, 1.0), (12, 52, 1.0)]


def test_head_write_slot_stride_zero_fixes_slot():
    """``slot_stride=0`` keeps the SLOT fixed while the DIM advances (the K
    one-hot-presence / AX_CARRY loops — all writes land on ONE K row). This is
    the directive that the STACK0/AX carry heads need; a default
    ``slot_stride=1`` would scatter the presence loop across rows and drift the
    whole-model hash (the exact bug the migration's byte-identity gate caught)."""
    out = _expand_head_writes(
        (HeadWrite(1, "H", 6.0, count=4, slot_stride=0),),
        lambda n: {"H": 67}[n], kind="proj")
    assert [(w.slot, w.dim, w.weight) for w in out] == [
        (1, 67, 6.0), (1, 68, 6.0), (1, 69, 6.0), (1, 70, 6.0)]
    assert all(w.slot == 1 for w in out)  # the fixed-row invariant


def test_head_write_out_directive_emits_ao():
    """``kind='out'`` emits ``AO(out_dim, slot, weight)`` per cell."""
    out = _expand_head_writes(
        (HeadWrite(10, "BAND", 1.0, count=2),),
        lambda n: {"BAND": 800}[n], kind="out")
    assert [(w.out_dim, w.slot, w.weight) for w in out] == [
        (800, 10, 1.0), (801, 11, 1.0)]


