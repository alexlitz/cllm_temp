def _parse_extra_residual_dims_env():
    """Parse ``C4_EXTRA_RESIDUAL_DIMS`` into a ``{name: size}`` dict.

    Format: ``"NAME:SIZE,NAME:SIZE"`` (e.g. ``"H1_PREV_STEP:16,FOO:32"``).
    Returns ``None`` when the env var is unset/empty so the production
    geometry stays byte-identical. Used to exercise the compiler's
    head-dim-preserving auto-widen path (the requested bands grow d_model
    to a multiple of the base head_dim and add heads).
    """
    raw = os.environ.get("C4_EXTRA_RESIDUAL_DIMS", "").strip()
    if not raw:
        return None
    out = {}
    for entry in raw.split(","):
        entry = entry.strip()
        if not entry:
            continue
        name, _, size = entry.partition(":")
        out[name.strip()] = int(size.strip())
    return out or None


class AutoregressiveVMRunner:
    """Generation loop for the autoregressive VM.

    Analogous to an LLM inference loop:
    - Build context (system prompt): bytecode + data + argv as tokens
    - Generate tokens autoregressively (model forward + greedy decode)
    - Detect I/O boundary (output bytes, halt)

    Supports two I/O modes:
    1. Legacy mode (conversational_io=False): Python handlers for I/O syscalls
    2. Conversational mode (conversational_io=True): Truly autoregressive I/O
       - Output: Model generates </thinking>, output text, <thinking>
       - Input: Model extracts from <user_input> tags in context
       - All I/O is part of the token stream (100% autoregressive)
    """

    # Module-level cache of fully-built models, keyed by config tuple.
    # Construction (set_vm_weights) is expensive (~10s); session-scoped tests
    # already cache via fixtures, but this cache helps across processes that
    # build many runners. Phase 0 (2026-05-09).
    _MODEL_CACHE = {}

    def __init__(
        self,
        d_model=None,
        n_layers=None,
        n_heads=DEFAULT_N_HEADS,
        ffn_hidden=DEFAULT_FFN_HIDDEN,
        max_seq_len=4096,
        pure_attention_memory=False,
        conversational_io=False,
        debug_ent_lev=False,
        debug_memory=False,
        use_kv_cache=True,
        max_mem_history=64,
        trust_neural_alu=False,
        pure_neural=False,
        cache_model=True,
        enable_neural_io_think_protocol=False,
        enable_kv_cache_pruning=False,
        kv_cache_pruning_min_size=256,
        kv_cache_pruning_tau=0.99,
        kv_cache_pruning_eps=1e-6,
        enable_divergence_bail=True,
        compile_mode=None,
        spec_k=0,
        enable_cuda_graphs=False,
        enable_moe_routing=False,
        csr_inference: Optional[bool] = None,
        compact_gather: Optional[bool] = None,
    ):
        """Initialize the autoregressive VM runner.

        Args:
            d_model: Residual stream dimension. None (default) means derive from
                the compiler (Phase 0 M6).
            n_layers: Number of transformer blocks. None (default) means derive
                from the compiler.
            trust_neural_alu: If True, trust neural network for ALU operations.
            pure_neural: If True, skip ALL Python overrides and run purely
                        autoregressively.
            enable_neural_io_think_protocol: If True, route PUTCHAR through the
                model-emitted ``THINKING_END, byte, THINKING_START`` token
                stream (BLOG_SPEC.md:851 — canonical neural-I/O mode) instead
                of the Phase-6 runner-reads-AX path. Defaults False; see
                ``c4_release/docs/NEURAL_IO_VIA_THINK_PROTOCOL_PLAN.md``.
            enable_divergence_bail: If True (default), detect pathological
                autoregressive loops and bail out early — returning whatever
                AX is in context. Lets failing pure_neural tests fail in
                seconds instead of hitting the pytest timeout. Set False for
                debug runs where you want to see the full token stream.

                Primary signal is ``draft_divergence``: per emitted token
                the model's argmax is compared against the deterministic
                prediction of a :class:`DraftVM` synced from the runner's
                last_pc/ax/sp/bp state. When the rolling-window mismatch
                rate climbs above 0.5 (>=25 of last 50 tokens disagree),
                the model has clearly stopped tracking the correct trace
                and we bail. The older heuristic signals
                (``pc_stuck_at_zero``, ``pc_repeating``,
                ``exec_idx_cycle``, ``no_step_end``) are retained as a
                fallback for runs where DraftVM cannot interpret the
                bytecode (``_draft_vm`` is None).
            compile_mode: Pass-through to ``torch.compile``. One of:
                ``None`` / ``"none"`` (do not compile; default),
                ``"reduce-overhead"`` (CUDA-graph capture),
                ``"max-autotune"`` (kernel autotune), or any string accepted
                by ``torch.compile(mode=...)``. Default ``None``: callers
                must opt in to compile explicitly. Auto-enabling compile
                conflicts with the byte-identity KV-cache tests, which need
                the un-compiled incremental path to still be exercised.

                Caveat (2026-05-12): the production model has ~30 blocks
                with distinct FFN shapes after right-sizing + post-op
                expansion. Compiling the whole forward causes Dynamo to
                re-trace per block under default settings; the runner sets
                ``recompile_limit=128`` and
                ``force_parameter_static_shapes=False`` to mitigate, but
                first-run compilation can still take minutes. Subsequent
                runs at the same seq-length should reuse the cached
                graphs. CUDA-graphs (``reduce-overhead``) additionally
                requires an output-buffer mark via
                ``torch.compiler.cudagraph_mark_step_begin()`` between
                successive outer ``run()`` calls — the runner inserts
                this automatically.
            spec_k: Number of full VM steps to speculate per batched forward
                in the serial generation loop. ``0`` (default) preserves the
                legacy one-forward-per-token behavior. When ``> 0`` and
                ``pure_neural=True``, a per-run :class:`DraftVM` emits the
                deterministic next ``spec_k * STEP_TOKENS`` tokens; the model
                verifies them in one forward pass and accepts the matching
                prefix. Byte-identity with ``spec_k=0`` is preserved because
                the model emission overrides any mismatching draft (the model
                is the final arbiter). Recommended starting point: ``spec_k=8``
                (matches :class:`BatchedPureNeuralRunner`'s default for the
                1098 suite).
            enable_cuda_graphs: Opt-in flag for manual CUDA-graph capture
                of the per-step forward. Currently a stub: setting True raises
                ``NotImplementedError``. The exploratory benchmark in
                ``c4_release/neural_vm/cuda_graph_bench.py`` found that
                manual capture is ~3× **slower** than eager for this model
                (compute-bound). See ``c4_release/docs/CUDA_GRAPHS_MULTI_STEP.md``.
            enable_moe_routing: If True, request
                ``compile_full_vm_dynamic(enable_moe_routing=True)`` so the compiler
                emits a model whose eligible FFN layers are already
                partitioned into per-opcode ``StandardMoEFFN`` experts plus a
                shared FFN. This is the standard top-K MoE path
                (Mixtral/DeepSeek/Qwen-style): only the K experts selected by
                the OP_* one-hot router run per token. For C4 ``top_k=1`` is
                the natural choice.

                Defaults False until the MoE-on smoke gate is promoted to the
                primary testing path. The compiler-owned transform is cached
                separately from the dense model.
            csr_inference: If True and the model lives on CUDA, the
                compiled dense weights are converted to ``torch.sparse_csr``
                in place after the build (see
                ``c4_release/neural_vm/base_layers.py:csr_sparsify_model``).
                Per the 2026-06-06 sparse benchmark
                (``c4_release/docs/SPARSE_INFERENCE_BENCHMARK_2026_06_06.md``),
                CSR gives ~2.1x CUDA forward-pass speedup at 99.9% argmax
                agreement vs dense. The 0.1% divergence is fp32 summation
                order noise: acceptable for explicit production inference,
                NOT for byte-identity test gates. ``None`` (default) reads
                ``C4_CSR_INFERENCE`` and otherwise keeps the dense model.
                The CSR model is cached separately from the dense model so
                both can coexist. CPU runs skip the conversion (CSR helps
                less and the benchmark target is GPU).
            compact_gather: If True, the compiled dense weights are
                pre-shrunk in place after the build to only the columns
                with any nonzero rows / heads with any active K/V/Q/O
                (see ``c4_release/neural_vm/base_layers.py
                :compact_gather_model``). Per the same 2026-06-06
                benchmark, this yields a 1.17x CUDA forward-pass speed-up
                at **100% argmax match and max abs diff 0.0** vs dense —
                byte-identical, because the dense GEMM kernel is unchanged
                and the gather just removes rows/columns whose
                contribution to every dot product is already zero.
                ``None`` (default) reads ``C4_COMPACT_GATHER`` and
                otherwise keeps the dense model. The compact-gather model
                is cached separately from the dense model so both can
                coexist. Mutually exclusive with ``csr_inference``: the
                two transforms touch the same parameters in different
                ways, so combining them is unsupported.
        """
        if enable_cuda_graphs:
            raise NotImplementedError(
                "AutoregressiveVMRunner: enable_cuda_graphs=True is a stub. "
                "Manual CUDA-graph capture was prototyped and found to be "
                "slower than eager forward on this model (compute-bound). "
                "See c4_release/docs/CUDA_GRAPHS_MULTI_STEP.md for the "
                "investigation and tradeoff analysis."
            )
        self.enable_cuda_graphs = bool(enable_cuda_graphs)
        # Phase 0 M5 (2026-05-09): the entire model build+bake goes through
        # compile_full_vm_dynamic. The compiler derives d_model and n_layers from the
        # operation set (no hardcoding) and orchestrates the bake pass.
        # Override d_model/n_layers via explicit args only for tests.
        alu_mode = 'efficient' if trust_neural_alu else 'lookup'
        # Normalize compile_mode to a plain "none" sentinel when not set.
        if compile_mode is None:
            compile_mode = "none"
        if csr_inference is None:
            # Default ON. CSR matmul gives 2.11× speedup at B=8 and up to
            # 3.51× at B=128 with 99.9% argmax match (fp32 sum-order noise
            # — see SPARSE_INFERENCE_BENCHMARK_2026_06_06.md). Opt out with
            # ``C4_CSR_INFERENCE=0`` for byte-identity-required test paths.
            _csr_env = os.environ.get("C4_CSR_INFERENCE", "1").strip().lower()
            csr_inference = _csr_env not in {"0", "false", "no", "off"}
        if compact_gather is None:
            compact_gather = (
                os.environ.get("C4_COMPACT_GATHER", "").strip().lower()
                in {"1", "true", "yes", "on"}
            )
        if csr_inference and compact_gather:
            raise ValueError(
                "AutoregressiveVMRunner: csr_inference=True and "
                "compact_gather=True are mutually exclusive — both transforms "
                "rewrite block.attn / block.ffn weight parameters in place."
            )
        cache_key = (d_model, n_layers, n_heads, ffn_hidden, max_seq_len,
                     conversational_io, alu_mode,
                     enable_neural_io_think_protocol, compile_mode,
                     bool(enable_moe_routing),
                     bool(csr_inference),
                     bool(compact_gather),
                     # Auto-widen bands change d_model/n_heads — keep widened
                     # and baseline models in separate cache slots.
                     os.environ.get("C4_EXTRA_RESIDUAL_DIMS") or None)
        if cache_model and cache_key in AutoregressiveVMRunner._MODEL_CACHE:
            self.model = AutoregressiveVMRunner._MODEL_CACHE[cache_key]
            # Re-install the CSR F.linear shim defensively in case the
            # process was forked / a non-CSR runner reset F.linear back
            # to the real one. The shim is idempotent.
            self._csr_info = None
            if csr_inference:
                from .base_layers import install_csr_linear_shim
                install_csr_linear_shim()
        else:
            from .unified_compiler.full_vm_compiler_dynamic import compile_full_vm_dynamic
            # Auto-widen passthrough: ``C4_EXTRA_RESIDUAL_DIMS`` (a
            # "name:size,name:size" string) requests fresh residual bands
            # so the compiler auto-grows d_model (rounded to a multiple of
            # the base head_dim, adding heads) without an op hardcoding
            # d_model. Off by default => byte-identical production geometry.
            _extra_dims = _parse_extra_residual_dims_env()
            self.model, _layout = compile_full_vm_dynamic(
                enable_conversational_io=conversational_io,
                enable_neural_io_think_protocol=enable_neural_io_think_protocol,
                alu_mode=alu_mode,
                n_heads=n_heads,
                ffn_hidden=ffn_hidden,
                max_seq_len=max_seq_len,
                enable_moe_routing=enable_moe_routing,
                strict=False,
                extra_residual_dims=_extra_dims,
            )
            if torch.cuda.is_available():
                self.model = self.model.cuda()
            self.model.eval()
            # Standard top-K MoE routing is emitted by
            # compile_full_vm_dynamic(enable_moe_routing=True) so the compiler/cache
            # owns the structural transform and compiled graphs see the
            # final module topology.
            # CSR sparse-inference conversion (commit cb0f396f bench:
            # 2.11x CUDA speedup at 99.9% argmax-match). Applied AFTER
            # the model is on its target device but BEFORE torch.compile
            # so the compiled graph sees CSR weights and the F.linear
            # shim. CPU and low-sparsity models are skipped automatically
            # by csr_sparsify_model's internal gates.
            self._csr_info = None
            if csr_inference:
                from .base_layers import csr_sparsify_model
                # compile_full_vm_dynamic has its own in-process memo that
                # returns the same model object for identical compiler kwargs.
                # CSR conversion mutates parameters in place, so isolate the
                # inference variant before converting or a CSR runner can
                # contaminate the dense runner/cache entry.
                if torch.cuda.is_available():
                    import copy
                    self.model = copy.deepcopy(self.model)
                self._csr_info = csr_sparsify_model(self.model)
            # Compact-gather inference: column-shrink dense weights to only
            # active rows/columns. Byte-identical (max diff 0.0, 100%
            # argmax) per the 2026-06-06 sparse benchmark, 1.17x CUDA
            # speedup. Applied AFTER device move but BEFORE torch.compile
            # so the compiled graph sees the smaller submatrices. Same
            # in-place isolation discipline as CSR: deepcopy the model if
            # it came from compile_full_vm_dynamic's process-wide memo so
            # we don't contaminate the dense cache entry.
            self._compact_gather_info = None
            if compact_gather:
                from .base_layers import compact_gather_model
                if torch.cuda.is_available():
                    import copy
                    self.model = copy.deepcopy(self.model)
                self._compact_gather_info = compact_gather_model(
                    self.model, block_size=1, compact_attn=False,
                )
            if compile_mode and compile_mode != "none":
                # The model has ~30 blocks with distinct FFN shapes (each
                # block was right-sized by ``_right_size_ffns``). Compiling
                # the whole model's ``forward`` as one frame causes Dynamo
                # to retrace per-block because ``block.ffn.W_up`` has a
                # different shape on each iteration of the ``for block
                # in self.blocks`` loop. The default
                # ``recompile_limit=8`` is too low for ~30 blocks, so we
                # bump it. Each retrace specializes Inductor to that
                # block's shapes; subsequent forwards reuse the cached
                # graphs.
                #
                # Why compile the whole model (not each block individually)?
                # Per-block ``block.compile()`` creates one CUDA graph
                # per block under ``reduce-overhead``, and each block's
                # captured-graph output buffer aliases its input buffer
                # — which means the *next* block's CUDA graph reads from
                # a buffer the previous graph has reused. This raises
                # "tensor output of CUDAGraphs that has been overwritten
                # by a subsequent run". Wrapping the entire forward as
                # one compile unit captures one big graph (no inter-block
                # reuse), avoiding that hazard.
                import torch._dynamo as _dynamo
                _dynamo.config.recompile_limit = max(
                    _dynamo.config.recompile_limit, 128
                )
                # Each block has different parameter shapes (post
                # ``_right_size_ffns``). Disabling
                # ``force_parameter_static_shapes`` lets Dynamo treat
                # parameter shapes as dynamic across the per-block sub-
                # frames, so it folds them into one shared trace instead
                # of guarding on the exact size of the first block's
                # ``W_up`` and recompiling for every subsequent block.
                _dynamo.config.force_parameter_static_shapes = False
                # Standard-recipe (2026-05-12): force ``dynamic=True`` so
                # the seq-dim is traced symbolically. Without this, Dynamo
                # specializes on the exact seq_len it sees on the first
                # forward and recompiles for every new seq_len during
                # autoregressive decoding (the "9 distinct sizes" warning).
                # See ``c4_release/docs/TORCH_COMPILE_BENCHMARK.md`` for the
                # full benchmark trail (Recipes A/B/C). The data-dependent
                # ``.item()`` early-outs (efficient_alu_divmod_split.py:459
                # et al.) are guarded by ``torch.compiler.is_compiling()``
                # so the compiled graph runs the full pipeline.
                self.model = torch.compile(
                    self.model, mode=compile_mode, dynamic=True
                )
            if cache_model:
                AutoregressiveVMRunner._MODEL_CACHE[cache_key] = self.model
        self.compile_mode = compile_mode

        # Wave B removal (2026-06-09): handler-mode syscall shims
        # (_syscall_prtf / _syscall_open / _syscall_read / _syscall_clos)
        # deleted. The handler-mode TOOL_CALL branch in `run()` now
        # dispatches against an empty table; IO opcodes raise honest
        # neural failures until the bakes tracked in
        # docs/IO_NEURAL_BAKE_QUEUE_2026_06_09.md land.
        self._syscall_handlers = {}

        # File descriptor tracking
        self._open_fds = {}  # fd → name

        # Bump allocator state
        self._heap_base = 0x10000  # Start of heap

        # Conversational I/O mode flag
        # When True, I/O operations are handled autoregressively:
        # - Output (printf/putchar): Model generates THINKING_END, output text, THINKING_START
        # - Input (read/getchar): Model extracts from USER_INPUT section in context
        # When False, I/O operations use Python handlers (legacy mode)
        self.conversational_io = conversational_io
        self._heap_ptr = 0x10000  # Current allocation pointer
        self._alloc_sizes = {}  # addr → size (for FREE zero-fill)

        # V5 SCOPE-LIMITED (2026-05-12): ``_memory`` (addr → uint8) is the
        # runner-side shadow byte memory. After V10 retire it has TWO
        # remaining categories of readers, both at the VM/host boundary:
        #   1. Syscall-shim format/path-string walkers
        #      (`_read_string`, `_neural_prtf_emit`,
        #      `_neural_open_emit`) — these resolve the C-string at a
        #      pointer baked into the bytecode. V9 territory; will
        #      retire when the conversational-IO neural-side PRTF/OPEN
        #      bake replaces the host-side walker.
        #   2. Handler-mode VM-semantic LI/LC/SI/SC fallbacks
        #      (`_dispatch_step` handler branch) — only reached when
        #      ``pure_neural=False``. Phase-7 territory.
        # No code path outside (1) and (2) reads ``_memory``. In
        # pure_neural mode only (1) is active.
        self._memory = {}

        # SP tracking for multi-byte correctness (PSH/ADJ handlers use this)
        self._last_sp = 0

        # PC tracking for exec_pc computation (function-call dispatch)
        self._last_pc = None

        # BP tracking for ENT/LEV handlers
        self._last_bp = 0

        # AX tracking for multi-byte preservation across steps.
        # Weights carry byte 0 only; runner re-applies bytes 1-3 each step.
        self._last_ax = 0

        # Debug flags
        self._debug_ent = debug_ent_lev
        self._debug_lev = debug_ent_lev
        self._debug_memory = debug_memory

        # KV cache (autoregressive K/V reuse).
        #
        # ``torch.compile`` interaction: the per-layer KV cache mutates
        # ``layer_cache.cached_k / cached_v`` in place from Python, which
        # ``torch.compile`` cannot trace cleanly. When a ``compile_mode`` is
        # active we therefore disable the incremental KV-cache fast path
        # and let each forward call process the full token sequence — the
        # compiled graph reuses the same CUDA-graph capture across calls.
        if compile_mode and compile_mode != "none":
            self.use_kv_cache = False
        else:
            self.use_kv_cache = use_kv_cache
        # V6 RETIRED (2026-05-12): ``_mem_history`` (addr → 9-token MEM
        # section) and its LRU companion ``_mem_access_order`` previously
        # held a Python-side mirror of past stores that the V10 shim
        # re-emitted into the live context every step. With V10 retired
        # the LRU has no readers; the attributes remain as empty dicts /
        # lists only because external diag/profile scripts still assign
        # ``runner._mem_history = {}`` defensively. ``max_mem_history``
        # is retained as an accepted-but-ignored constructor arg for the
        # same reason (existing tests pass it through). All three are
        # slated for full deletion once those call sites migrate.
        self.max_mem_history = max_mem_history
        self._mem_history = {}
        self._mem_access_order = []

        # If True: disable runner VM-memory emulation paths and only allow
        # explicit external tool boundary handling.
        self.pure_attention_memory = pure_attention_memory
        self.trust_neural_alu = trust_neural_alu
        self.pure_neural = pure_neural
        # Phase 1 neural-I/O THINK-tag protocol scaffolding.
        # When True, the runner accepts THINKING_END/byte/THINKING_START tokens
        # interleaved into the model's PUTCHAR step output (BLOG_SPEC.md:851).
        # When False (default), the legacy AX-readoff path at run_vm.py:827-828
        # collects PUTCHAR bytes. The compiler-side bake for this is gated by
        # the same flag (``make_putchar_think_protocol_op``); both paths are
        # currently no-ops until the follow-up bake commit lands the weight
        # wiring (see NEURAL_IO_VIA_THINK_PROTOCOL_PLAN.md).
        self.enable_neural_io_think_protocol = enable_neural_io_think_protocol
        # Output-collection state for the THINK-tag protocol. Set True when
        # the model emits THINKING_END; cleared when it emits THINKING_START.
        # Byte tokens (0-255) seen while True are appended to ``output`` in
        # the runner's main loop, bypassing the AX-readoff PUTCHAR path.
        self._neural_io_collecting_byte = False
        self._pure_attention_report = {}
        self._phase6_syscall_events = []

        # KV cache pruning (KV_CACHE_PRUNING_SPEC.md §2.1 + §2.2).
        # Defaults OFF: byte-identity vs cache-off requires no pruning.
        # When enabled, ``run()`` invokes ``prune_kv_cache`` at every
        # STEP_END boundary (cheap because the pruner short-circuits when
        # ``cache_size <= min_cache_size``).
        self.enable_kv_cache_pruning = bool(enable_kv_cache_pruning)
        self.kv_cache_pruning_min_size = int(kv_cache_pruning_min_size)
        self.kv_cache_pruning_tau = float(kv_cache_pruning_tau)
        self.kv_cache_pruning_eps = float(kv_cache_pruning_eps)
        # Per-run stats counter for visibility / debugging.
        self._kv_pruning_stats = {"calls": 0, "evicted_total": 0,
                                  "evicted_by_similarity": 0,
                                  "evicted_by_zero_v": 0}

        # MoE routing flag — recorded for diagnostic visibility.
        # ``compact()`` + ``compact_moe()`` already ran above (gated by
        # the same flag), so this is purely informational at the runner
        # level.
        self.enable_moe_routing = bool(enable_moe_routing)

        # Divergence-bail configuration. When True (default), ``run`` watches
        # for pathological autoregressive states and breaks out of the
        # generation loop returning the partial output. Primary signal is
        # ``draft_divergence`` (per-token compare against a deterministic
        # :class:`DraftVM`); heuristic signals (``pc_stuck_at_zero`` /
        # ``pc_repeating`` / ``exec_idx_cycle`` / ``no_step_end``) remain
        # as fallback when DraftVM is unavailable. Disable for debug runs
        # where the full token stream is required.
        self.enable_divergence_bail = enable_divergence_bail
        # Bail-state diagnostics from the most recent `run()`. Populated only
        # when a divergence signal fires; otherwise None.
        self.last_divergence_signal = None
        # DraftVM (deterministic Python C4 interpreter) — instantiated per
        # ``run()`` call inside ``_init_draft_vm``. The per-step draft
        # tokens it produces drive the primary ``draft_divergence`` bail
        # signal. ``None`` outside of a run() or when DraftVM is disabled.
        self._draft_vm: Optional[DraftVM] = None
        self._draft_step_tokens: Optional[List[int]] = None

        # Speculative-decoding configuration. ``spec_k`` is the number of full
        # VM steps a per-run :class:`DraftVM` emits per batched forward pass.
        # 0 disables speculation entirely (legacy single-token autoregressive
        # loop). Speculation is only honored when ``pure_neural=True`` because
        # the non-pure path's ``_dispatch_step`` mutates state per-token (PSH
        # SP decrement, JSR/LEV stack rewrites, etc.) which is incompatible
        # with replaying a batch of accepted draft tokens.
        self.spec_k = int(spec_k) if spec_k else 0
        # Per-run draft state. ``_draft_vm`` is the Python C4 interpreter used
        # to propose deterministic next-N tokens; ``_spec_disabled_for_run``
        # is flipped if the model rejects the first draft for several iters
        # in a row (DraftVM out of sync) so we stop wasting forwards.
        self._draft_vm = None
        self._spec_disabled_for_run = False
        self._spec_zero_streak = 0
        self._spec_should_break = False

    # Maximum number of consecutive incremental forward calls before flushing
    # the KV cache. Empirically, the c4 VM model's L15 (memory-lookup) attention
    # uses very steep softmax that amplifies float non-associativity in the
    # incremental matmul path; after ~34 incremental calls in a row the drift
    # accumulates enough to flip an argmax. Flushing the cache periodically
    # forces a single full forward (no cache) call which resets the drift to
    # zero. ``35`` matches one VM step (the natural boundary) and was verified
    # to yield byte-identical output across multiple programs.
    _KV_INCREMENTAL_FLUSH = 35

    # DraftVM-divergence bail thresholds. Window is 50 tokens (~1.4 VM
    # steps of 35 tokens each); threshold of 0.5 means >=25 of the last
    # 50 tokens disagree with DraftVM. The window/threshold pair is sized
    # so a well-behaved program (occasional 1-2 mismatches around MEM
    # addr/val from spec-vs-unspec embedding metadata) never trips, while
    # a model that has lost the plot (PC stuck at 0, AX random, etc.)
    # trips within roughly one VM step of bad output.
    _DRAFT_BAIL_WINDOW = 50
    _DRAFT_BAIL_RATE = 0.5

    def _init_draft_vm(self, bytecode, data, stdin):
        """Build a fresh :class:`DraftVM` for divergence-detection.

        Returns ``None`` if divergence-bail is disabled (no DraftVM needed)
        or if DraftVM construction fails (e.g. unsupported bytecode). Loads
        the data section into DraftVM memory the same way ``run()`` loads
        it into ``self._memory``, and primes stdin so the deterministic
        interpreter sees the same input the runner does.
        """
        if not self.enable_divergence_bail:
            return None
        try:
            vm = DraftVM(list(bytecode))
        except Exception:
            return None
        data = data or b""
        if isinstance(data, (bytes, bytearray)):
            for i, b in enumerate(data):
                vm.memory[0x10000 + i] = int(b)
        elif isinstance(data, list):
            for i, b in enumerate(data):
                vm.memory[0x10000 + i] = int(b)
        if stdin:
            vm.set_stdin(stdin)
        return vm

    def _sync_draft_vm_from_runner(self):
        """Pull register state from the runner into ``self._draft_vm``.

        Memory is not transplanted: ``self._memory`` is byte-addressed
        while :class:`DraftVM`'s ``memory`` is word-addressed. Register
        drift is the dominant correctness signal for divergence; memory
        drift just produces extra mismatches (acceptable — divergence-bail
        tolerates some natural disagreement via the sliding-window rate).
        """
        vm = self._draft_vm
        if vm is None:
            return
        if self._last_pc is not None:
            vm.pc = int(self._last_pc) & 0xFFFFFFFF
            vm.idx = (vm.pc - PC_OFFSET) // INSTR_WIDTH
        vm.ax = int(self._last_ax) & 0xFFFFFFFF
        vm.sp = int(self._last_sp) & 0xFFFFFFFF
        vm.bp = int(self._last_bp) & 0xFFFFFFFF
        vm.halted = False
        vm._last_mem_addr = 0
        vm._last_mem_val = 0

    def _refresh_draft_step(self):
        """Advance ``self._draft_vm`` by one instruction and stash its 35
        draft tokens into ``self._draft_step_tokens``.

        Called at every STEP_END / TOOL_CALL boundary. On the first call
        (before any model emission) ``self._last_pc`` may still be None;
        in that case we skip the sync and let DraftVM run from its
        constructor-initialized state (PC=PC_OFFSET, AX=0, SP=BP=STACK_INIT).
        """
        vm = self._draft_vm
        if vm is None:
            self._draft_step_tokens = None
            return
        if self._last_pc is not None:
            self._sync_draft_vm_from_runner()
        try:
            advanced = vm.step()
        except Exception:
            # DraftVM choked on this instruction — give up on the draft
            # signal for the rest of the run. The heuristic fallback
            # signals are still active.
            self._draft_vm = None
            self._draft_step_tokens = None
            return
        if not advanced:
            # DraftVM is halted or out of code — nothing to compare against.
            self._draft_step_tokens = None
            return
        self._draft_step_tokens = vm.draft_tokens()

    def _reset_kv_cache(self):
        """Reset/clear the autoregressive attention KV cache.

        Called at the start of each ``run()`` and whenever the runner detects
        that the cached prefix has been invalidated (active_opcode change,
        major context shift, etc.). Lazily-allocates the LayerKVCache on first
        use (after we know the device + layer count from the model).
        """
        self._kv_cache_obj = None
        self._kv_cached_tokens = []  # tokens currently represented in the cache
        self._kv_cached_opcode = object()  # sentinel; mismatch on first call
        self._kv_incremental_count = 0  # number of consecutive incremental calls

    def _get_or_build_kv_cache(self):
        """Lazily build the LayerKVCache, sized to match the model.

        Returns None when ``use_kv_cache`` is disabled.
        """
        if not self.use_kv_cache:
            return None
        if self._kv_cache_obj is not None:
            return self._kv_cache_obj
        from .kv_cache import LayerKVCache
        n_layers = len(self.model.blocks)
        # We don't actually use ``num_heads``/``head_dim`` on the LayerKVCache
        # itself because the per-layer caches just store whatever K/V tensors
        # the attention layer passes in; only ``max_tokens`` matters for the
        # sliding-window evict path, which we set generously here.
        device = next(self.model.parameters()).device
        self._kv_cache_obj = LayerKVCache(
            num_layers=n_layers,
            max_tokens=self.model.max_seq_len,
            num_heads=self.model.blocks[0].attn.num_heads,
            head_dim=self.model.blocks[0].attn.head_dim,
            device=device,
        )
        self._kv_cached_tokens = []
        return self._kv_cache_obj

    def _preload_kv_cache_with_prefix(self, prefix_tokens):
        """Eagerly populate the KV cache with K/V for the immutable prefix.

        The CODE/DATA/argv prefix (positions 0..``len(prefix_tokens)``) does
        not change within a single ``run()``. We run one forward pass over
        the prefix with a freshly-allocated cache so that every subsequent
        ``_generate_next_cached`` call only needs to compute K/V for the
        newly-appended tokens.

        This replaces the retired ``NeuralVMEmbedding`` prefix-embedding-delta
        cache (V20). The KV cache subsumes it cleanly: it stores the actual
        K/V tensors that attention reads, not just the embedding-layer
        modifications. No-op when ``use_kv_cache`` is False.

        Args:
            prefix_tokens: List of integer token IDs comprising the immutable
                prefix (typically the output of ``_build_context``).
        """
        if not self.use_kv_cache:
            return
        if not prefix_tokens:
            return
        kv_cache = self._get_or_build_kv_cache()
        device = next(self.model.parameters()).device
        token_ids = torch.tensor([prefix_tokens], dtype=torch.long, device=device)
        with torch.no_grad():
            # cached_prefix_len=0: this is the first call into the cache; the
            # full prefix becomes the cached state.
            self.model.forward(
                token_ids,
                kv_cache=kv_cache,
                cached_prefix_len=0,
            )
        self._kv_cached_tokens = list(prefix_tokens)
        # Reset the incremental-flush counter so the preload itself doesn't
        # count against the per-step flush budget.
        self._kv_incremental_count = 0
        # Match the current model active_opcode so the next
        # ``_generate_next_cached`` call does not see a sentinel mismatch and
        # discard the preload. ``_active_opcode`` was retired with the
        # StandardMoEFFN migration so ``cur_opcode`` is ``None`` in practice, but
        # we use the same getattr pattern as the generator to stay in sync.
        self._kv_cached_opcode = getattr(self.model, "_active_opcode", None)

    def _kv_common_prefix_len(self, new_tokens):
        """Length of the longest matching leading subsequence of ``new_tokens``
        with the currently-cached tokens.
        """
        cached = self._kv_cached_tokens
        n = min(len(cached), len(new_tokens))
        i = 0
        while i < n and cached[i] == new_tokens[i]:
            i += 1
        return i

    def _maybe_prune_kv_cache(self, context, prefix_len):
        """Run the two-rule KV pruner at a STEP_END boundary.

        No-op unless ``self.enable_kv_cache_pruning`` and the cache exists.

        Note on the prefix-reuse mirror: the runner tracks
        ``_kv_cached_tokens`` as a *dense* list whose i-th entry is the
        token at cache index ``i``. Pruning removes middle positions, so
        the cache is no longer a strict prefix of the runner's context.
        The cleanest way to preserve correctness without rewriting the
        prefix-match logic is to invalidate the runner-side mirror after
        a pruning event (forcing a full rebuild on the next forward).
        This trades a one-step cache miss for the memory savings of the
        prune. ``cached_pos_ids`` still survives in the underlying
        ``LayerKVCache`` for any future call paths that want to use
        position-aware reuse.
        """
        if not self.enable_kv_cache_pruning:
            return
        if self._kv_cache_obj is None:
            return
        layer0 = self._kv_cache_obj.caches[0] if self._kv_cache_obj.caches else None
        if layer0 is None or layer0.cached_k is None:
            return
        if layer0.cache_size <= self.kv_cache_pruning_min_size:
            return

        from .kv_cache_pruning import prune_kv_cache

        # The pruner needs a token-id sequence aligned with the K/V sequence
        # axis. We feed ``_kv_cached_tokens`` which is the runner's
        # ground-truth mirror of "what's in the cache, in order".
        cache_seq = self._kv_cached_tokens
        if len(cache_seq) < layer0.cache_size:
            # Defensive: skip when the mirror is out-of-sync with the
            # tensor (shouldn't happen, but better than a crash).
            return

        stats = prune_kv_cache(
            self._kv_cache_obj,
            cache_seq,
            prefix_len=prefix_len,
            tau=self.kv_cache_pruning_tau,
            eps=self.kv_cache_pruning_eps,
            min_cache_size=self.kv_cache_pruning_min_size,
        )

        if stats.total_evicted > 0:
            self._kv_pruning_stats["calls"] += 1
            self._kv_pruning_stats["evicted_total"] += stats.total_evicted
            self._kv_pruning_stats["evicted_by_similarity"] += stats.evicted_by_similarity
            self._kv_pruning_stats["evicted_by_zero_v"] += stats.evicted_by_zero_v
            # Invalidate the prefix-match mirror: the cache is no longer a
            # contiguous prefix of the context. ``_kv_cached_tokens=[]``
            # forces the next ``_kv_common_prefix_len`` to return 0, which
            # triggers a full cache rebuild. We also clear the underlying
            # cache to keep the two in lockstep.
            self._reset_kv_cache()

    def _trim_kv_cache(self, keep_len):
        """Trim per-layer caches to ``keep_len`` positions.

        Used when the input sequence shares only ``keep_len`` leading tokens
        with the cached state (e.g. last position was overwritten, or a middle
        slice changed). Layers' K/V at positions ``>= keep_len`` are dropped.
        """
        if self._kv_cache_obj is None:
            return
        for layer_cache in self._kv_cache_obj.caches:
            if layer_cache.cached_k is None:
                continue
            cur = layer_cache.cache_size
            if keep_len >= cur:
                continue
            if keep_len <= 0:
                layer_cache.cached_k = None
                layer_cache.cached_v = None
                layer_cache.cached_pos_ids = None
                layer_cache.cache_size = 0
                layer_cache.next_pos_id = 0
            else:
                layer_cache.cached_k = layer_cache.cached_k[:, :, :keep_len, :]
                layer_cache.cached_v = layer_cache.cached_v[:, :, :keep_len, :]
                if layer_cache.cached_pos_ids is not None:
                    layer_cache.cached_pos_ids = layer_cache.cached_pos_ids[:, :keep_len]
                layer_cache.cache_size = keep_len
                # Rewind the next-position counter so subsequent appends
                # continue contiguously from ``keep_len``. The cache mirror
                # is a strict prefix here (trim only removes the tail), so
                # positions stay 0..keep_len-1.
                layer_cache.next_pos_id = keep_len
        # Also trim the tracking list.
        self._kv_cached_tokens = self._kv_cached_tokens[:keep_len]

    def _generate_next_cached(self, generation_context):
        """Generate next token reusing per-layer KV caches across forward calls.

        Behavior:
        - If ``use_kv_cache`` is False or the model's current ``_active_opcode``
          differs from the cached opcode, falls back to a fresh forward pass
          and rebuilds the cache from scratch.
        - Otherwise computes the longest matching leading subsequence between
          ``generation_context`` and the currently-cached tokens; trims the
          per-layer caches to that length; runs the model on only the new
          tokens (``cached_prefix_len`` argument).

        Returns:
            int: argmax-decoded next-token id (matches ``model.generate_next``
            with ``temperature=0.0``).
        """
        if not self.use_kv_cache:
            # When ``torch.compile`` is active, call ``self.model(...)``
            # directly so the OptimizedModule's __call__ is invoked
            # (and the compiled graph runs). ``model.generate_next`` is a
            # method on the underlying ``AutoregressiveVM`` and would call
            # the un-compiled forward.
            if self.compile_mode and self.compile_mode != "none":
                device = next(self.model.parameters()).device
                # ``max_seq_len`` lives on the original AutoregressiveVM;
                # we just call ``self.model(...)`` directly so each block's
                # compiled forward runs.
                max_seq_len = getattr(self.model, "max_seq_len", None)
                ctx = list(generation_context)
                if max_seq_len is not None and len(ctx) > max_seq_len:
                    ctx = ctx[-max_seq_len:]
                token_ids = torch.tensor([ctx], dtype=torch.long, device=device)
                # Recipe A (2026-05-12): on the FIRST compiled forward,
                # mark the seq dim as dynamic with explicit bounds. This
                # tells Dynamo to produce a single graph parameterized
                # over the seq dim, instead of specializing on the exact
                # seq_len of this call. Subsequent calls with different
                # seq_len reuse the compiled graph. The runner caches
                # ``_marked_dynamic_seq`` so we only call ``mark_dynamic``
                # once per process — repeated calls are warned on (and
                # are no-ops anyway once the guard is established).
                if not getattr(self, "_marked_dynamic_seq", False):
                    try:
                        import torch._dynamo as _dynamo
                        _dynamo.mark_dynamic(
                            token_ids, 1,
                            min=1,
                            max=max_seq_len or 2048,
                        )
                    except Exception:
                        # ``mark_dynamic`` may not exist on older PyTorch
                        # versions or may fail on a non-eager tensor.
                        # Compile still works (just without the explicit
                        # symbolic bound); fall back silently.
                        pass
                    self._marked_dynamic_seq = True
                # ``reduce-overhead`` captures a CUDA graph per compiled
                # submodule and reuses an output buffer across calls. We
                # must mark a "step boundary" before each top-level forward
                # so the previous step's output buffers are released for
                # reuse (otherwise the second call raises "tensor output of
                # CUDAGraphs has been overwritten"). This is a no-op when
                # CUDA graphs aren't actually in use (e.g. CPU / non-RO
                # modes).
                torch.compiler.cudagraph_mark_step_begin()
                with torch.no_grad():
                    logits = self.model(token_ids)
                return int(logits[0, -1, :].argmax(-1).item())
            return self.model.generate_next(generation_context, use_incremental=False)

        # Active opcode is part of the embedding (writes globally at all
        # positions when in the injection set). When it changes, the cached
        # K/V at past positions are stale, so we invalidate.
        cur_opcode = getattr(self.model, "_active_opcode", None)
        if cur_opcode != self._kv_cached_opcode:
            self._reset_kv_cache()
            self._kv_cached_opcode = cur_opcode

        # Periodically flush the cache to bound the accumulated float-drift
        # caused by non-associativity in the incremental matmul path. The
        # affected attention layer (L15, ``num_heads=12``, memory lookup)
        # uses very steep softmax over binary-address-matching keys; small
        # numerical drift in upstream K/V (computed via a long chain of
        # successive 1-token matmuls vs a single batch matmul) compounds
        # and flips an argmax. Empirically the threshold is ~35 incremental
        # calls (one VM step); we conservatively flush at that boundary.
        if self._kv_incremental_count >= self._KV_INCREMENTAL_FLUSH:
            self._reset_kv_cache()
            self._kv_cached_opcode = cur_opcode

        kv_cache = self._get_or_build_kv_cache()
        prefix_len = self._kv_common_prefix_len(generation_context)
        self._trim_kv_cache(prefix_len)

        # Build the token tensor on the model's device.
        device = next(self.model.parameters()).device
        token_ids = torch.tensor([generation_context], dtype=torch.long, device=device)

        # Run model.forward with cached_prefix_len. When prefix_len == len(context)
        # there are zero new tokens — uncommon (would mean we asked for next-token
        # twice with identical context); in that case run a normal forward.
        if prefix_len >= len(generation_context):
            # No new tokens — re-run on full context (rare; defensive).
            self._reset_kv_cache()
            self._kv_cached_opcode = cur_opcode
            logits = self.model.forward(token_ids, kv_cache=self._get_or_build_kv_cache(),
                                        cached_prefix_len=0)
            next_token = logits[0, -1, :].argmax(-1).item()
            self._kv_cached_tokens = list(generation_context)
            return next_token

        with torch.no_grad():
            logits = self.model.forward(
                token_ids,
                kv_cache=kv_cache,
                cached_prefix_len=prefix_len,
            )
        # When cached_prefix_len > 0, logits has shape [1, new_tokens, vocab];
        # the next-token prediction is the LAST position.
        next_token = logits[0, -1, :].argmax(-1).item()
        self._kv_cached_tokens = list(generation_context)
        self._kv_incremental_count += 1
        return next_token

    def run(
        self,
        bytecode,
        data=b"",
        argv=None,
        stdin="",
        max_steps=100000,
        tool_handler=None,
    ):
        """Run a program via autoregressive generation.

        Args:
            bytecode: List of packed instructions (op | imm<<8)
            data: Data section bytes
            argv: List of argument strings
            stdin: Input string
            max_steps: Maximum VM steps (each step = 39 tokens)
            tool_handler: Optional callback(ToolCall) -> ToolResponse for I/O

        Returns:
            (output_string, exit_code) tuple
        """
        self._bytecode = bytecode
        # Wave D removal (2026-06-10): ``_stdin_buffer`` / ``_stdin_pos``
        # deleted. The neural GETCHAR bake reads stdin bytes from the
        # USER_INPUT_START/END region of the token stream directly; the
        # READ/PRTF host-syscall shims that used to consume this buffer
        # have already been removed (Wave B, 2026-06-09).
        self._tool_handler = tool_handler
        self._tool_call_id = 0
        self._last_pc = None
        self._last_bp = 0x10000  # Initial BP (same as model embedding STACK_INIT)
        self._last_sp = 0x10000  # Initial SP (same as model embedding STACK_INIT)
        # Track last dispatched instruction index for observation only.
        self._last_dispatched_idx = -1
        # Reset THINK-tag protocol collector so leftover state from a prior
        # run() (e.g. truncated PUTCHAR step without a closing THINKING_START)
        # does not bleed into the next program.
        self._neural_io_collecting_byte = False
        self._mem_history = {}  # addr → 9-token MEM section (latest wins)
        self._mem_access_order = []  # LRU tracking: most recent at end
        self.model.embed.set_mem_history_end(0)  # reset stale boundary from prior runs
        # Reset the KV cache for autoregressive attention (per-run state).
        # ``self.use_kv_cache`` (constructor arg) gates this; when True the
        # runner reuses K/V across forward calls, recomputing only the new
        # tokens beyond the longest matching prefix.
        self._reset_kv_cache()
        self._pure_attention_report = {
            "enabled": bool(self.pure_attention_memory),
            "blocked_vm_memory_ops": {},
            "blocked_track_memory_ops": {},
            "external_tool_ops": {},
            "halted": False,
        }
        self._phase6_syscall_events = []

        # Load data section into shadow memory at 0x10000
        # C4 compiler uses data_base = 0x10000 (src/compiler.py:339)
        data = data or b""
        if isinstance(data, (bytes, bytearray)):
            for i, b in enumerate(data):
                self._memory[0x10000 + i] = b
        elif isinstance(data, list):
            for i, b in enumerate(data):
                self._memory[0x10000 + i] = b

        # Set heap base past end of data section, aligned to 8
        data_end = 0x10000 + len(data)
        self._heap_base = (data_end + 7) & ~7
        self._heap_ptr = self._heap_base

        context = self._build_context(bytecode, data, argv or [], stdin)
        prefix_len = len(context)  # code + data prefix length (immutable)
        output = []

        # Preload the per-layer KV cache with the immutable CODE/DATA/argv
        # prefix. The prefix never changes within a single ``run()``, so its
        # K/V tensors are reusable across every subsequent forward call.
        # Without this preload, the first ``_generate_next_cached`` call would
        # process the entire prefix from scratch; with it, the very first
        # autoregressive step only needs to compute K/V for the newly-appended
        # tokens. This replaces the retired ``NeuralVMEmbedding`` prefix
        # cache (V20 in PURITY_AUDIT_2026_05_11.md): the KV cache subsumes
        # its role at the proper level (transformer K/V, not embedding deltas).
        self._preload_kv_cache_with_prefix(context)

        # The MoE routing signal is read tensor-natively inside StandardMoEFFN
        # (see neural_vm.pure_moe); no Python-side bytecode peek required.

        # Speculative-decoding gate: only honored when pure_neural=True. The
        # non-pure path's _dispatch_step mutates state per-token (PSH SP, JSR
        # stack rewrites, runner ALU corrections) which is incompatible with
        # replaying a batch of accepted draft tokens in one shot.
        if self.spec_k > 0 and self.pure_neural:
            self._draft_vm = DraftVM(list(bytecode))
            # Load data section into DraftVM memory (byte-addressed, matching
            # the runner's _memory convention) so PRTF/READ in DraftVM see
            # the same initial state.
            if isinstance(data, (bytes, bytearray, list)):
                for di, b in enumerate(data):
                    self._draft_vm.memory[0x10000 + di] = int(b)
            if stdin:
                self._draft_vm.set_stdin(stdin)
            self._spec_disabled_for_run = False
            self._spec_zero_streak = 0
            return self._run_speculative(
                context, bytecode, prefix_len, output, max_steps
            )

        step_num = 0  # Track VM steps for conversational I/O handling

        # ---- Divergence-bail detection state (per-run) ----
        # See ``enable_divergence_bail`` docstring on ``__init__``. We watch
        # for pathological autoregressive states that indicate the model has
        # lost the plot and would just spin until the pytest timeout.
        #
        # Primary signal is ``draft_divergence``: per emitted token the
        # model's argmax is compared to a :class:`DraftVM`'s deterministic
        # prediction. When the rolling-window mismatch rate climbs above
        # ``_DRAFT_BAIL_RATE`` over ``_DRAFT_BAIL_WINDOW`` tokens we bail.
        # Heuristic signals (pc_stuck_at_zero / pc_repeating /
        # exec_idx_cycle / no_step_end) remain as fallback for runs where
        # DraftVM cannot interpret the bytecode (``_draft_vm`` is None).
        self.last_divergence_signal = None
        pc_history = deque(maxlen=10)
        exec_idx_history = deque(maxlen=10)
        steps_since_last_step_end = 0
        dispatch_count = 0  # number of VM steps actually dispatched

        # DraftVM: deterministic Python C4 interpreter (produces 35 draft
        # tokens per step in the same format the transformer generates).
        # Constructed fresh per ``run()`` so prior runs don't leak state.
        self._draft_vm = self._init_draft_vm(bytecode, data, stdin)
        self._draft_step_tokens = None
        # Sliding window of bool: True == model disagreed with DraftVM at
        # that token position. Window size and rate set by class constants.
        draft_mismatch_history = deque(maxlen=self._DRAFT_BAIL_WINDOW)
        # Per-VM-step position counter (0..34). Reset to 0 on every
        # STEP_END / TOOL_CALL boundary. Used to index into
        # ``self._draft_step_tokens`` for the per-token compare.
        draft_step_pos = 0
        # Prime the first draft step (before any model emission).
        if self._draft_vm is not None:
            self._refresh_draft_step()

        def _bail_check():
            """Return a (signal_name, detail) tuple if divergence detected, else None.

            Called only after a successful `_dispatch_step` (i.e. at STEP_END /
            TOOL_CALL), so `pc_history` and `exec_idx_history` reflect post-
            dispatch state. We need at least a few dispatched steps before any
            check can fire — otherwise a fresh program with last_pc=0 would
            bail immediately.
            """
            # Signal 1: PC stuck at 0 for >=5 consecutive dispatched steps
            # (model lost PC tracking; last_pc has collapsed to 0).
            if len(pc_history) >= 5 and dispatch_count > 3:
                last5 = list(pc_history)[-5:]
                if all(p == 0 for p in last5):
                    return ("pc_stuck_at_zero",
                            f"last 5 PCs all 0 after {dispatch_count} dispatched steps")

            # Signal 2: PC repeating a single non-zero value for >=5 consecutive
            # steps (infinite loop on one instruction — never advancing by
            # INSTR_WIDTH).
            if len(pc_history) >= 5:
                last5 = list(pc_history)[-5:]
                if last5[0] != 0 and all(p == last5[0] for p in last5):
                    return ("pc_repeating",
                            f"last 5 PCs all 0x{last5[0]:x} (no advance)")

            # Signal 3: exec_idx oscillates over a tiny set near program start
            # (model collapsed; e.g. bouncing between exec_idx 0 and 1 forever).
            # Conservative form: full 10-entry window must (a) contain at most
            # 3 distinct exec_idx values, all in [0, 5], AND (b) PC history
            # over the same window contains at most 3 distinct values. Legit
            # C loops typically have larger PCs and/or longer bodies and won't
            # trip this gate.
            if (len(exec_idx_history) == exec_idx_history.maxlen
                    and len(pc_history) == pc_history.maxlen):
                ei_set = set(exec_idx_history)
                pc_set = set(pc_history)
                if (len(ei_set) <= 3
                        and max(ei_set) <= 5
                        and len(pc_set) <= 3):
                    return ("exec_idx_cycle",
                            f"exec_idx oscillating over {sorted(ei_set)} "
                            f"with PC set {sorted(pc_set)} (model collapsed)")

            return None


        # Context windowing prevents O(n²) blowup while preserving CODE section.
        # The CODE section (bytecode) is needed for L5 fetch heads to read instructions.
        # Keep prefix (CODE + DATA) + last 512 tokens of dynamic content (MEM + steps).
        for i in range(max_steps * Token.STEP_TOKENS):
            # Apply context windowing preserving prefix (CODE/DATA sections)
            # Without prefix, model can't attend to bytecode for instruction fetch
            if len(context) > prefix_len + 512:
                generation_context = context[:prefix_len] + context[-512:]
            else:
                generation_context = context
            next_token = self._generate_next_cached(generation_context)
            context.append(next_token)

            # Re-anchor the per-step compare position to the model's own
            # step structure. ``DraftVM.draft_tokens()`` always lays a step
            # out as ``[REG_PC, ...]`` (REG_PC is draft offset 0). The model
            # marks the start of every emitted VM step with the same REG_PC
            # token, but its real step length is not rigidly 35 tokens — it
            # occasionally emits a stray boundary token, which slips
            # ``draft_step_pos`` permanently out of phase with the DraftVM
            # reference after the first step. That phase slip made ~half of
            # the per-token compares spuriously mismatch on short, correct
            # programs (e.g. the smoke CMP/MEM tests), pushing the 50-token
            # window over ``_DRAFT_BAIL_RATE`` and tripping a FALSE
            # ``draft_divergence`` bail that truncated execution before the
            # result was computed. That false bail is why the spec_k=0 serial
            # path diverged from the spec_k>0 serial path (which has no bail)
            # and from the batched ``spec_k=0`` smoke gate. Re-anchoring on
            # REG_PC keeps the compare in phase with the model's actual step
            # boundaries; genuine divergence (wrong VALUE bytes after the
            # marker) still trips the window. ``draft_step_pos`` is reset
            # BEFORE the compare so the REG_PC token itself lines up with
            # draft offset 0.
            if next_token == Token.REG_PC and self._draft_step_tokens is not None:
                draft_step_pos = 0

            # Primary divergence signal: compare against DraftVM's
            # deterministic prediction for this token offset within the
            # current VM step. The 50-token sliding window absorbs the
            # natural occasional mismatch (MEM addr/val embedding-metadata
            # corner cases, transient model noise) while still tripping
            # within roughly one VM step of a true divergence. See class
            # constants ``_DRAFT_BAIL_WINDOW``, ``_DRAFT_BAIL_RATE``.
            if (self.enable_divergence_bail
                    and self._draft_step_tokens is not None
                    and draft_step_pos < len(self._draft_step_tokens)):
                draft_tok = self._draft_step_tokens[draft_step_pos]
                draft_mismatch_history.append(next_token != draft_tok)
            draft_step_pos += 1

            if (self.enable_divergence_bail
                    and self._draft_vm is not None
                    and len(draft_mismatch_history) == draft_mismatch_history.maxlen):
                mismatches = sum(draft_mismatch_history)
                window = len(draft_mismatch_history)
                if mismatches / window >= self._DRAFT_BAIL_RATE:
                    self.last_divergence_signal = (
                        "draft_divergence",
                        f"{mismatches} of last {window} tokens disagree with DraftVM"
                    )
                    warnings.warn(
                        "AutoregressiveVMRunner.run: divergence detected — "
                        f"{self.last_divergence_signal[0]}: "
                        f"{self.last_divergence_signal[1]}. Bailing early.",
                        RuntimeWarning,
                        stacklevel=2,
                    )
                    break

            # Fallback signal #4: STEP_END never emitted for a long time
            # (model lost the well-formed-step structure entirely). Checked
            # every token so a runaway loop is caught even without dispatch.
            # Threshold = ~14 STEP_TOKENS-worth (35*14 = 490 → round to 500).
            #
            # GATED on ``self._draft_vm is None``: this heuristic produces
            # false positives on passing single-IMM tests where the model
            # correctly emits end-of-program tokens but doesn't reliably
            # interleave STEP_END (those tests still pass because
            # ``_decode_exit_code`` reads AX from context; the bail just
            # added a spurious warning). When DraftVM is available, the
            # ``draft_divergence`` primary signal is strictly stronger and
            # this fallback is suppressed to eliminate the false positives.
            # Bytecodes that DraftVM can't model fall back to this signal.
            steps_since_last_step_end += 1
            if (self.enable_divergence_bail
                    and self._draft_vm is None
                    and steps_since_last_step_end > 500):
                self.last_divergence_signal = (
                    "no_step_end",
                    f"no STEP_END for {steps_since_last_step_end} tokens"
                )
                warnings.warn(
                    "AutoregressiveVMRunner.run: divergence detected — "
                    f"{self.last_divergence_signal[0]}: "
                    f"{self.last_divergence_signal[1]}. Bailing early.",
                    RuntimeWarning,
                    stacklevel=2,
                )
                break

            pos_in_step = i % Token.STEP_TOKENS
            # Wave A removal (2026-06-09, df50a8c9): forced STEP_END
            # rewrite at pos 34 (#56) deleted. Pure forward-pass — the
            # model emits the step boundary itself.

            # Debug: Print step progress
            if self._debug_ent or self._debug_lev:
                if i % 35 == 0:  # Every step
                    pc = self._extract_register(context, Token.REG_PC) if len(context) > 20 else None
                    ax = self._extract_register(context, Token.REG_AX) if len(context) > 20 else None
                    pc_val = pc if pc is not None else 0
                    ax_val = ax if ax is not None else 0
                    print(f"[STEP {i//35}] token {i}/{max_steps * Token.STEP_TOKENS}, PC=0x{pc_val:08x}, AX=0x{ax_val:08x}", flush=True)

            # Phase 1 neural-I/O THINK-tag protocol (BLOG_SPEC.md:851).
            # When enabled, the model emits THINKING_END at the end of a
            # PUTCHAR step (replacing STEP_END), then a byte token, then
            # THINKING_START, then a real STEP_END. The runner collects the
            # byte into ``output`` and ignores the bookkeeping tokens.
            #
            # Gated by ``enable_neural_io_think_protocol`` so the existing
            # AX-readoff path (run_vm.py:827-828) remains the default until
            # the full PRTF/GETCHAR/READ bake chain lands. See
            # ``c4_release/docs/NEURAL_IO_VIA_THINK_PROTOCOL_PLAN.md``.
            if self.enable_neural_io_think_protocol:
                if next_token == Token.THINKING_END:
                    self._neural_io_collecting_byte = True
                    continue
                if next_token == Token.THINKING_START:
                    self._neural_io_collecting_byte = False
                    continue
                if self._neural_io_collecting_byte and 0 <= next_token < 256:
                    # Byte token while in the THINKING_END..THINKING_START
                    # block: emit to user-visible output stream.
                    output.append(chr(next_token & 0xFF))
                    continue

            # Wave A removal (2026-06-09, df50a8c9): hybrid
            # conversational-IO THINKING_END branch (#38) + synthetic-
            # step injection (#39) deleted. The Python format-string
            # walk + synthetic 35-token step was a cheat. PRTF must
            # come through the neural THINK protocol bake chain
            # (l6_ops.py:4387 prtf_think_protocol). Until that bake
            # lands, conversational_io=True is unsupported.

            if next_token == Token.STEP_END:
                if step_num < 3:
                    step_num += 1  # Increment step counter
                # Extract PC and identify opcodes
                op = None
                instr_idx = None
                if step_num <= 3:
                    exec_pc = self._exec_pc()  # PC being executed this step
                if step_num <= 3:
                    pc = self._extract_register(context, Token.REG_PC)  # Next PC from output
                if step_num <= 3:
                    # Get opcode being executed this step
                    exec_idx = exec_pc // INSTR_WIDTH
                    exec_op = None
                    exec_opname = "?"
                    if 0 <= exec_idx < len(bytecode):
                        exec_op = bytecode[exec_idx] & 0xFF
                        # Find opcode name
                        for name in dir(Opcode):
                            if not name.startswith('_') and getattr(Opcode, name) == exec_op:
                                exec_opname = name
                                break

                # BUG FIX 2026-04-16: Dispatch func_call_handlers BEFORE syscall_handlers.
                # func_call_handlers process the CURRENT instruction (exec_pc) and set
                # _last_ax correctly. syscall_handlers process the NEXT instruction (output pc)
                # and may read _last_ax. If syscall runs first, _last_ax gets clobbered.
                # Example: PSH step - handler should set STACK0=_last_ax, but _syscall_prtf
                # (for next instruction) was running first and setting _last_ax=0.

                exec_idx = self._exec_pc() // INSTR_WIDTH
                if self._dispatch_step(context, bytecode, exec_idx, prefix_len, output):
                    break

                # STEP_END boundary is the natural place to invoke KV cache
                # pruning (KV_CACHE_PRUNING_SPEC.md §3.2). No-op unless
                # ``enable_kv_cache_pruning=True`` was passed to ``__init__``.
                self._maybe_prune_kv_cache(context, prefix_len)

                # Divergence detection: update post-dispatch state and check
                # for pathological signals. STEP_END resets the no-STEP_END
                # counter; PC/exec_idx history feeds the cycle / stuck checks.
                steps_since_last_step_end = 0
                pc_history.append(self._last_pc if self._last_pc is not None else 0)
                exec_idx_history.append(exec_idx)
                dispatch_count += 1
                # Advance DraftVM by one instruction and stash the next 35
                # draft tokens; reset the per-step position counter so
                # subsequent token compares line up correctly.
                if self._draft_vm is not None:
                    self._refresh_draft_step()
                draft_step_pos = 0
                # Heuristic fallback bail: gated on DraftVM unavailable so
                # we don't double-fire. The primary ``draft_divergence``
                # signal already fires within the per-token check above.
                if self.enable_divergence_bail and self._draft_vm is None:
                    signal = _bail_check()
                    if signal is not None:
                        self.last_divergence_signal = signal
                        warnings.warn(
                            "AutoregressiveVMRunner.run: divergence detected — "
                            f"{signal[0]}: {signal[1]}. Bailing early after "
                            f"{dispatch_count} dispatched steps.",
                            RuntimeWarning,
                            stacklevel=2,
                        )
                        break

            elif next_token == Token.TOOL_CALL:
                # Wave D removal (2026-06-10): handler-mode TOOL_CALL
                # syscall-handler dispatch + _track_memory_write deleted.
                # TOOL_CALL must resolve neurally; the model is the sole
                # arbiter of register/memory state.
                exec_idx = self._exec_pc() // INSTR_WIDTH
                if self._dispatch_step(context, bytecode, exec_idx, prefix_len, output):
                    break

                # Divergence detection: mirror the STEP_END branch above.
                steps_since_last_step_end = 0
                pc_history.append(self._last_pc if self._last_pc is not None else 0)
                exec_idx_history.append(exec_idx)
                dispatch_count += 1
                if self._draft_vm is not None:
                    self._refresh_draft_step()
                draft_step_pos = 0
                if self.enable_divergence_bail and self._draft_vm is None:
                    signal = _bail_check()
                    if signal is not None:
                        self.last_divergence_signal = signal
                        warnings.warn(
                            "AutoregressiveVMRunner.run: divergence detected — "
                            f"{signal[0]}: {signal[1]}. Bailing early after "
                            f"{dispatch_count} dispatched steps.",
                            RuntimeWarning,
                            stacklevel=2,
                        )
                        break

            # Halt detection
            if next_token == Token.HALT:
                # Wave A removal (2026-06-09, df50a8c9): handler-mode
                # REG_AX re-assert at HALT (#58) deleted. The model's
                # emitted bytes are the result; _decode_exit_code reads
                # them directly.
                self._pure_attention_report["halted"] = True
                break

        return "".join(output), self._decode_exit_code(context)

    # ------------------------------------------------------------------
    # Speculative-decoding loop (serial, pure_neural=True only).
    #
    # Mirrors BatchedPureNeuralRunner._run_speculative but for batch=1 with
    # the full per-token dispatch path of the legacy autoregressive loop.
    # DraftVM emits the deterministic next K*35 tokens; the model verifies
    # them in a single forward pass and accepts the matching prefix. Byte-
    # identity with spec_k=0 is preserved because the model's argmax is the
    # final arbiter (mismatching drafts are rejected and replaced).
    # ------------------------------------------------------------------
    @torch.no_grad()
    def _run_speculative(self, context, bytecode, prefix_len, output, max_steps):
        """Speculative-decoding generation loop (pure_neural=True path).

        Args:
            context: token list (mutated). On entry, holds the prefix
                produced by :meth:`_build_context`.
            bytecode: packed-instruction list for DraftVM and dispatch.
            prefix_len: number of immutable prefix tokens (CODE/DATA/argv).
            output: list to which PUTCHAR / PRTF bytes are appended.
            max_steps: maximum VM steps; the loop emits at most
                ``max_steps * STEP_TOKENS`` tokens.

        Returns:
            ``(output_str, exit_code)`` matching the legacy ``run()`` signature.
        """
        STEP = Token.STEP_TOKENS
        total_tokens = max_steps * STEP
        spec_k = self.spec_k

        # Token-emission counter (mirrors `i` in the legacy loop). When the
        # next emitted token is at a clean VM-step boundary we attempt
        # speculation; otherwise we single-token decode until the next
        # boundary (no different from the legacy path for those positions).
        token_pos = 0
        # Flag set by ``_apply_token_spec`` when EXIT or HALT dispatch decides
        # the run is over. Mirrors the ``break`` in the legacy loop.
        self._spec_should_break = False

        while token_pos < total_tokens:
            if self._spec_should_break:
                break

            # Once the DraftVM drifts far enough from the model's emission
            # that we've seen 4 zero-accept iters in a row, drop out of
            # speculation entirely and finish via the legacy KV-cached
            # path. This is dramatically faster than per-token fresh
            # forwards for the remainder of the run because the cache lets
            # each forward process only the new token; the spec-path
            # always processes the full windowed context.
            if self._spec_disabled_for_run:
                self._run_speculative_fallback_kv_cached(
                    context, bytecode, prefix_len, output,
                    start_i=token_pos, total_tokens=total_tokens,
                )
                break

            at_step_boundary = (token_pos % STEP == 0)

            # Windowed context (matches the legacy path's 512-token tail).
            if len(context) > prefix_len + 512:
                gen_ctx = context[: prefix_len] + context[-512:]
            else:
                gen_ctx = list(context)

            # Cap the draft horizon to the compiled model/cache window. The
            # batched runner already does this; the serial path needs the
            # same guard because very long fixed K values can otherwise build
            # verifier tensors longer than the model's KV cache can represent
            # as a strict prefix.
            model_max_seq = int(getattr(self.model, "max_seq_len", len(gen_ctx)))
            room_tokens = max(0, model_max_seq - len(gen_ctx))
            effective_spec_k = min(spec_k, room_tokens // STEP)

            # Build draft only when we are at a clean step boundary. Mid-
            # step we fall back to one-token decode (still through this
            # method) so per-step dispatch state (e.g. mem_history rebuild)
            # stays correctly aligned.
            draft: List[int] = []
            if (
                effective_spec_k > 0
                and at_step_boundary
                and self._draft_vm is not None
            ):
                self._sync_draft_vm_from_runner()
                for _ in range(effective_spec_k):
                    if self._draft_vm.halted:
                        break
                    if not self._draft_vm.step():
                        break
                    draft.extend(self._draft_vm.draft_tokens())
                    if self._draft_vm.halted:
                        break

            # Build the full sequence (windowed prefix + drafts) and run a
            # single verifier forward. When KV caching is enabled, reuse the
            # common prefix and recompute from the final context token onward:
            # logits at position ``prefix_end - 1`` are what verify draft[0],
            # so caching through ``prefix_end`` would skip the first verifier
            # logit we need.
            seq = gen_ctx + draft
            prefix_end = len(gen_ctx)
            preds, pred_start, _used_kv = self._forward_speculative_verifier(
                seq,
                first_logit_pos=max(0, prefix_end - 1),
            )

            if not draft:
                # Pure single-token decode (no spec budget this iter — only
                # happens for the first iter post-spec-rejection while we
                # re-align to a step boundary; the disabled-spec branch
                # above handles the long-term fallback).
                next_token = int(preds[prefix_end - 1 - pred_start])
                self._apply_token_spec(
                    context, next_token, token_pos, bytecode, prefix_len, output
                )
                if self._spec_should_break:
                    break
                token_pos += 1
                continue

            # Verify drafts position-by-position. Unsafe offsets are trusted
            # from DraftVM; safe offsets are accepted only when model argmax
            # matches. First-rejected safe offset stops the scan and the
            # model's prediction becomes the correction token.
            accepted = 0
            correction: Optional[int] = None
            for j in range(len(draft)):
                if (j % STEP) in _SPEC_UNSAFE_OFFSETS:
                    accepted = j + 1
                    continue
                pred = int(preds[prefix_end - 1 + j - pred_start])
                if pred == draft[j]:
                    accepted = j + 1
                else:
                    correction = pred
                    break

            emitted: List[int] = list(draft[:accepted])
            if correction is not None:
                emitted.append(correction)

            for tok in emitted:
                if self._spec_should_break:
                    break
                self._apply_token_spec(
                    context, tok, token_pos, bytecode, prefix_len, output
                )
                token_pos += 1

            # Cap consecutive zero-accept iterations: if the model rejects
            # the very first draft token several iters in a row the DraftVM
            # is out of sync (or never matches for this program); disable
            # speculation for the remainder of the run. The next iter will
            # detect ``_spec_disabled_for_run`` and switch to the legacy
            # KV-cached path via ``_run_speculative_fallback_kv_cached``.
            if correction is not None and accepted == 0:
                self._spec_zero_streak += 1
                if self._spec_zero_streak >= 4:
                    self._spec_disabled_for_run = True
            else:
                self._spec_zero_streak = 0

        return "".join(output), self._decode_exit_code(context)

    def _forward_speculative_verifier(self, seq, *, first_logit_pos):
        """Run a speculative verifier forward and return argmax tokens.

        ``first_logit_pos`` is the earliest absolute position in ``seq`` whose
        next-token logits the caller will inspect. For speculative decoding
        this is the final real-context token, because that logit verifies the
        first drafted token. The KV cache may therefore cover only positions
        strictly before ``first_logit_pos``.

        Returns:
            ``(preds, pred_start, used_kv)`` where ``preds[k]`` is the argmax
            for absolute sequence position ``pred_start + k``.
        """
        device = next(self.model.parameters()).device
        tensor = torch.tensor([seq], dtype=torch.long, device=device)

        if not self.use_kv_cache:
            logits = self.model.forward(tensor)
            return logits[0].argmax(dim=-1).cpu().tolist(), 0, False

        cur_opcode = getattr(self.model, "_active_opcode", None)
        if cur_opcode != self._kv_cached_opcode:
            self._reset_kv_cache()
            self._kv_cached_opcode = cur_opcode

        if self._kv_incremental_count >= self._KV_INCREMENTAL_FLUSH:
            self._reset_kv_cache()
            self._kv_cached_opcode = cur_opcode

        prefix_match = self._kv_common_prefix_len(seq)
        cached_prefix_len = min(prefix_match, int(first_logit_pos))
        self._trim_kv_cache(cached_prefix_len)

        kv_cache = self._get_or_build_kv_cache()
        logits = self.model.forward(
            tensor,
            kv_cache=kv_cache,
            cached_prefix_len=cached_prefix_len,
        )
        cached_preds = logits[0].argmax(dim=-1).cpu().tolist()

        # Correctness guard for incremental K/V reuse and eviction/trimming:
        # compare the cached verifier outputs against a fresh full-window
        # forward for every position the speculative verifier may inspect. If
        # they differ, invalidate the cache and make the fresh logits
        # authoritative. This keeps KV cache as an optimization only.
        fresh_logits = self.model.forward(tensor)
        fresh_preds = fresh_logits[0].argmax(dim=-1).cpu().tolist()
        fresh_tail = fresh_preds[cached_prefix_len:]
        if cached_preds != fresh_tail:
            self._reset_kv_cache()
            self._kv_cached_opcode = cur_opcode
            return fresh_preds, 0, False

        self._kv_cached_tokens = list(seq)
        self._kv_incremental_count += 1
        return cached_preds, cached_prefix_len, True

    def _run_speculative_fallback_kv_cached(
        self, context, bytecode, prefix_len, output,
        *, start_i, total_tokens,
    ):
        """Legacy KV-cached single-token loop, used when speculation is
        disabled mid-run.

        Mirrors the body of the legacy ``run()`` loop for ``pure_neural=True``
        from token index ``start_i`` onward. Resets the KV cache once on
        entry because the cache state from the spec-path's fresh-forward
        passes is stale: those forwards bypassed the cache machinery and
        the cache contents may not reflect the current ``context``. After
        reset, ``_generate_next_cached`` rebuilds the cache from scratch on
        the first call and uses incremental decoding thereafter.
        """
        # Drop any cache state inherited from the spec path; the spec
        # forwards bypass the cache so its contents are unrelated to the
        # current context. Without this reset, the prefix-match check in
        # `_generate_next_cached` would either find a stale match (wrong
        # K/V) or do a full recompute that wastes the first incremental
        # call.
        self._reset_kv_cache()
        for i in range(start_i, total_tokens):
            if self._spec_should_break:
                break
            if len(context) > prefix_len + 512:
                gen_ctx = context[: prefix_len] + context[-512:]
            else:
                gen_ctx = context
            next_token = self._generate_next_cached(gen_ctx)
            self._apply_token_spec(
                context, next_token, i, bytecode, prefix_len, output
            )

    def _sync_draft_vm_from_runner(self) -> None:
        """Pull current runner register state into the DraftVM.

        Memory is NOT copied: ``self._memory`` is byte-addressed while
        :class:`DraftVM` uses word-addressed storage (and tracks bytes
        separately in ``_mem_bytes``). Register drift is the dominant
        rejection driver; memory drift only causes extra rejections, which
        gracefully fall back to single-token decode for the affected step.
        """
        vm = self._draft_vm
        if vm is None:
            return
        if self._last_pc is not None:
            vm.pc = int(self._last_pc) & 0xFFFFFFFF
            vm.idx = (vm.pc - PC_OFFSET) // INSTR_WIDTH
        vm.ax = int(self._last_ax) & 0xFFFFFFFF
        vm.sp = int(self._last_sp) & 0xFFFFFFFF
        vm.bp = int(self._last_bp) & 0xFFFFFFFF
        vm.halted = False
        vm._last_mem_addr = 0
        vm._last_mem_val = 0

    def _apply_token_spec(
        self, context, next_token, i, bytecode, prefix_len, output
    ) -> None:
        """Apply one already-decided token to the run state.

        Mirrors the body of the legacy ``run()`` loop for a single token: it
        appends the token to ``context``, dispatches STEP_END / TOOL_CALL /
        HALT through ``_dispatch_step``, and flips ``_spec_should_break`` if
        the run should terminate (EXIT / HALT). The speculative outer loop
        in :meth:`_run_speculative` calls this for each accepted draft token
        plus any correction.

        Pure-neural-only paths (``self.pure_neural=True``): the THINK-tag
        protocol and conversational-IO branches are intentionally skipped
        because speculation is gated on ``pure_neural=True`` upstream and
        DraftVM does not produce THINKING_END/THINKING_START tokens.
        """
        context.append(next_token)

        if next_token == Token.STEP_END:
            exec_idx = self._exec_pc() // INSTR_WIDTH
            if self._dispatch_step(context, bytecode, exec_idx, prefix_len, output):
                self._spec_should_break = True
                return
            return

        if next_token == Token.TOOL_CALL:
            # pure_neural path: no Python-side handler, just dispatch for
            # EXIT detection (mirrors run() branch).
            exec_idx = self._exec_pc() // INSTR_WIDTH
            if self._dispatch_step(context, bytecode, exec_idx, prefix_len, output):
                self._spec_should_break = True
                return
            return

        if next_token == Token.HALT:
            # pure_neural: do NOT override REG_AX (model emitted it).
            self._pure_attention_report["halted"] = True
            self._spec_should_break = True
            return

